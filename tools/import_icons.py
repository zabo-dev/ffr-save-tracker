"""Copy the graphics the viewer uses from a texture export into icons/ and write icons/manifest.js.

The graphics belong to Square Enix and are not part of the repository (icons/ is git-ignored).
Extract them from your own copy of the game, e.g. with the bundled extractor:

  dotnet run --project tools/extractor -c Release -- "<...>\\FINAL FANTASY RESONANCE\\FFRS\\Content\\Paks" "<export folder>"
  python tools/import_icons.py "<export folder>"

An FModel PNG export of FFRS/Content/UI/Textures works the same way.

Usage: import_icons.py <export folder> [target folder, default: icons/]
"""
import json
import re
import shutil
import sys
from pathlib import Path

# (target folder, regex on the file name without .png, key). First match wins.
RULES = [
    ("chars", r"ICON_UnitFace_unit(100[1-8])", r"\1"),           # pixel faces of the 8 party members
    ("portraits", r"T_Chara_Menu_long_(100[1-8])", r"\1"),       # menu portraits
    ("visions", r"ICON_UnitFace_summon(13\d{3})", r"\1"),        # Vision sprites
    ("espers", r"ICON_UnitFace_summon(1045\d)", r"\1"),          # Esper sprites
    ("items", r"(ICON_Item_\w+)", r"\1"),                         # item type icons
    ("elements", r"ICON_Menu_(Fire|Ice|Wind|Ground|Thunder|Water|Light|Dark)", r"\1"),
    ("map", r"ICON_MAP_L_(\w+)", r"\1"),                          # map symbols (chest, cave, shrine, …)
    ("ui", r"(MenuIcon_FingerCursor_R|ICON_Menu_GILL|ICON_Result_EXP|ICON_Result_MRP|ICON_Quest_Clear|ICON_Quest_Check"
           r"|ICON_Menu_MainStory|ICON_Menu_SubStory|ICON_Menu_Reauest|ICON_Vision_Rank|T_TitleLogoText|T_EventStill_00)", r"\1"),
]


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "icons"
    if not src.is_dir():
        sys.exit(f"Folder not found: {src}")
    compiled = [(k, re.compile(p + "$"), r) for k, p, r in RULES]
    found = {k: set() for k, _, _ in RULES}
    for png in sorted(src.rglob("*.png")):
        for kind, rx, repl in compiled:
            m = rx.match(png.stem)
            if not m:
                continue
            name = m.expand(repl)
            # Vision/Esper faces exist twice; the Vision_Face variant wins
            if name in found[kind] and "Vision_Face" not in png.parts:
                break
            (dst / kind).mkdir(parents=True, exist_ok=True)
            shutil.copyfile(png, dst / kind / f"{name}.png")
            found[kind].add(name)
            break
    if not any(found.values()):
        sys.exit("No matching PNGs found. Was FFRS/Content/UI/Textures exported?")
    (dst / "manifest.js").write_text(
        "// Generated by tools/import_icons.py. Do not commit.\nwindow.FFR_ICONS=" + json.dumps({k: sorted(v) for k, v in found.items()}) + ";\n",
        encoding="utf-8")
    print(", ".join(f"{k}: {len(v)}" for k, v in found.items()), f"→ {dst}")


if __name__ == "__main__":
    main()
