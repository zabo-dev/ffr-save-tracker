"""Read DT_RequestData (side quests and substories) and write data/quests.js.

Each table row names the quest title (EventQuestTitle_NNN) and conditions such as "{progress:28}==40".
Counter progress:K is stored in the save at Progress.Progress[K], which tells how far a quest has progressed.

Usage: python tools/quests.py <export folder> [out=data/quests.js]
<export folder>: where the extractor wrote its --raw Datatable/Request/ export.
"""
import json
import re
import sys
from pathlib import Path

# Quests that share a counter or whose last stage is not in the table: completion value set by hand
DONE_AT = {36: 20, 42: 60, 43: 100, 47: 20, 51: 40, 52: None, 48: None, 45: None, 54: None}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]) / "FFRS/Content/Datatable/Request/DT_RequestData.uasset"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "data/quests.js"
    strings = [x.decode() for x in re.findall(rb"[\x20-\x7e]{4,}", src.read_bytes())]
    rows, cur = [], None
    for s in strings:
        if s.startswith("EventQuestTitle_"):
            cur = {"q": int(s.split("_")[1]), "conds": []}
            rows.append(cur)
        elif cur is not None and "{progress:" in s:
            cur["conds"].append(s)
    quests = []
    for r in rows:
        stages, start = {}, None
        for c in r["conds"]:
            for k, _, v in re.findall(r"\{progress:(\d+)\}(==|>=)(\d+)", c):
                k, v = int(k), int(v)
                if k == 0:
                    start = v if start is None else min(start, v)
                else:
                    stages.setdefault(k, set()).add(v)
        if not stages:
            continue
        k = max(stages, key=lambda key: len(stages[key]))
        vals = sorted(stages[k] - {0})
        done = DONE_AT.get(r["q"], vals[-1] if vals else None)
        quests.append({"q": r["q"], "k": k, "stages": [v for v in vals if done is None or v <= done], "done": done, "start": start})
    out.write_text("// Side quests from DT_RequestData (generated by tools/quests.py): title ID, save counter, stages, completion value.\n"
                   "const QUESTS=" + json.dumps(quests, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"{len(quests)} quests -> {out}")


if __name__ == "__main__":
    main()
